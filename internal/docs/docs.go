// Package docs generates the reference part of a test set's README from the
// suite definition, so the documented tests cannot drift from the real ones.
package docs

import (
	"fmt"
	"sort"
	"strings"

	"github.com/unknovs/goferret/internal/suite"
)

// Markers delimit the generated region inside a README.
const (
	Begin = "<!-- tests:begin (generated by `ferret docs`; do not edit) -->"
	End   = "<!-- tests:end -->"
)

// Generate renders the inputs table, the tag table and the full test list.
func Generate(s *suite.Suite) string {
	var b strings.Builder

	b.WriteString("### Inputs\n\n| Input | Type | Required | Secret | Description |\n| --- | --- | --- | --- | --- |\n")
	names := make([]string, 0, len(s.Contract.Inputs))
	for n := range s.Contract.Inputs {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		d := s.Contract.Inputs[n]
		typ := d.Type
		if typ == "" {
			typ = "string"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", n, typ, yesNo(d.Required), yesNo(d.Secret), esc(d.Description))
	}
	b.WriteString("\nEvery input can also be supplied as `<NAME>_FILE`, a path to a file holding the value.\n\n")

	// per tag counts, in declared order
	type count struct{ scenarios, assertions int }
	byTag := map[string]*count{}
	for _, t := range s.Tags {
		byTag[t] = &count{}
	}
	total := count{}
	for _, sc := range s.Loaded {
		a := assertions(sc)
		total.scenarios++
		total.assertions += a
		for _, t := range sc.Tags {
			if c := byTag[t]; c != nil {
				c.scenarios++
				c.assertions += a
			}
		}
	}
	b.WriteString("### Tags\n\nSelect with `--tag NAME` (repeatable, union) or skip with `--exclude-tag NAME`.\n\n| Tag | Scenarios | Assertions |\n| --- | ---: | ---: |\n")
	for _, t := range s.Tags {
		fmt.Fprintf(&b, "| `%s` | %d | %d |\n", t, byTag[t].scenarios, byTag[t].assertions)
	}
	fmt.Fprintf(&b, "\nAll scenarios: %d, assertions: %d. A scenario can carry several tags, so rows overlap.\n\n", total.scenarios, total.assertions)

	b.WriteString("### Tests\n\nEach scenario lists its steps and the named assertions it checks. Run one with `--scenario ID`.\n\n")
	for _, tag := range s.Tags {
		var rows []*suite.Scenario
		for _, sc := range s.Loaded {
			if len(sc.Tags) > 0 && sc.Tags[0] == tag {
				rows = append(rows, sc)
			}
		}
		if len(rows) == 0 {
			continue
		}
		fmt.Fprintf(&b, "#### %s\n\n", tag)
		for _, sc := range rows {
			fmt.Fprintf(&b, "<details><summary><code>%s</code> &mdash; %s (%d assertions)</summary>\n\n", sc.ID, esc(sc.Description), assertions(sc))
			for _, st := range sc.Steps {
				kind := ""
				if st.Helper {
					kind = " _(helper)_"
				}
				fmt.Fprintf(&b, "- **%s** `%s %s`%s\n", esc(st.ID), st.Method, esc(st.Path), kind)
				for _, g := range st.Assert {
					fmt.Fprintf(&b, "  - %s\n", esc(g.Name))
				}
			}
			for _, st := range sc.Cleanup {
				fmt.Fprintf(&b, "- **%s** `%s %s` _(cleanup)_\n", esc(st.ID), st.Method, esc(st.Path))
			}
			b.WriteString("\n</details>\n\n")
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

func assertions(sc *suite.Scenario) int {
	n := 0
	for _, st := range sc.Steps {
		if !st.Helper {
			n += len(st.Assert)
		}
	}
	return n
}

func yesNo(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

func esc(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "<", "&lt;")
	s = strings.ReplaceAll(s, ">", "&gt;")
	return strings.ReplaceAll(s, "\n", " ")
}

// Replace puts generated between the markers of readme. It returns an error
// when the markers are missing or out of order.
func Replace(readme, generated string) (string, error) {
	i := strings.Index(readme, Begin)
	j := strings.Index(readme, End)
	if i < 0 || j < 0 || j < i {
		return "", fmt.Errorf("README must contain the markers\n%s\n...\n%s", Begin, End)
	}
	return readme[:i+len(Begin)] + "\n\n" + generated + "\n" + readme[j:], nil
}
